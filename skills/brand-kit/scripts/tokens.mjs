#!/usr/bin/env node
/**
 * Design tokens from brand.json: writes tokens.css (colours in OKLCH with the hex kept as a
 * comment, font stacks, type settings) and prints a WCAG contrast report. No dependencies.
 *
 *   node tokens.mjs --brand brandkit/brand.json            # writes <kit>/tokens.css
 *   node tokens.mjs --brand brandkit/brand.json --strict   # exit 1 when a text pair fails AA
 *   node tokens.mjs --hex "#97FCE4"                        # convert one colour
 */
import { existsSync } from "node:fs";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const argv = process.argv.slice(2);
const flag = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i === -1 ? fallback : argv[i + 1];
};
const HEX = /^#[0-9a-fA-F]{6}$/;
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/[\s_]+/g, "-").toLowerCase();
const linear = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));

export function oklch(hex) {
  const [r, g, b] = linear(hex);
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s;
  const B = 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s;
  const C = Math.hypot(A, B);
  const H = C < 0.0005 ? 0 : ((Math.atan2(B, A) * 180) / Math.PI + 360) % 360;
  return `oklch(${(L * 100).toFixed(1)}% ${C.toFixed(3)} ${H.toFixed(1)})`;
}

export function contrast(a, b) {
  const lum = (hex) => {
    const [r, g, bl] = linear(hex);
    return 0.2126 * r + 0.7152 * g + 0.0722 * bl;
  };
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

async function main() {
  const one = flag("hex");
  if (one) {
    if (!HEX.test(one)) throw new Error("--hex takes a 6-digit hex such as #97FCE4");
    console.log(oklch(one));
    return;
  }
  const file = path.resolve(flag("brand", "brandkit/brand.json"));
  if (!existsSync(file)) throw new Error(`brand config not found: ${file}`);
  const brand = JSON.parse(await readFile(file, "utf8"));
  const out = path.resolve(path.dirname(file), brand.out ?? ".");
  const p = brand.palette ?? {};
  const colours = Object.entries(p).filter(([, v]) => HEX.test(v));
  if (!colours.length) throw new Error("brand.json: palette has no hex colour");

  const f = brand.fonts ?? {};
  const stack = (role, fallback) => (f[role]?.family ? `"${f[role].family}", ` : "") + fallback;
  const lines = [
    `/* ${brand.name} design tokens. Generated by tokens.mjs from brand.json: edit brand.json, then re-run. */`,
    ":root {",
    ...colours.map(([k, v]) => `  --color-${kebab(k)}: ${oklch(v)}; /* ${v.toUpperCase()}${brand.paletteRoles?.[k] ? ` · ${brand.paletteRoles[k]}` : ""} */`),
    "",
    `  --font-display: ${stack("display", "ui-sans-serif, system-ui, sans-serif")};`,
    `  --font-body: ${stack("body", "ui-sans-serif, system-ui, sans-serif")};`,
    `  --font-mono: ${stack("mono", "ui-monospace, SFMono-Regular, Menlo, monospace")};`,
    `  --display-weight: ${f.display?.weight ?? 600};`,
    `  --display-tracking: ${f.display?.tracking ?? "-0.03em"};`,
    `  --body-weight: ${f.body?.weight ?? 400};`,
    "}",
    "",
  ];
  await writeFile(path.join(out, "tokens.css"), lines.join("\n"));
  console.log(`ok  ${path.relative(process.cwd(), path.join(out, "tokens.css"))}\n`);

  // Pairs that carry text. AA: 4.5 for body text, 3 for large text and UI marks.
  const pairs = [
    ["text", "background", 4.5],
    ["text", "surface", 4.5],
    ["text", "raised", 4.5],
    ["muted", "background", 4.5],
    ["muted", "surface", 4.5],
    ["accent", "background", 3],
    ["accentText", "accent", 4.5],
    ["background", "accent", 4.5],
    ...(brand.contrastPairs ?? []),
  ].filter(([a, b]) => HEX.test(p[a] ?? "") && HEX.test(p[b] ?? ""));
  let failed = 0;
  console.log("contrast (WCAG 2.x)");
  for (const [a, b, min] of pairs) {
    const c = contrast(p[a], p[b]);
    const ok = c >= min;
    // "background on accent" only matters when the brand has no explicit accentText.
    const advisory = a === "background" && b === "accent" && p.accentText;
    if (!ok && !advisory) failed++;
    console.log(`  ${ok ? "pass" : advisory ? "info" : "FAIL"}  ${`${a} on ${b}`.padEnd(24)} ${c.toFixed(2)}:1  (needs ${min}:1)`);
  }
  if (failed) {
    console.log(`\n${failed} pair(s) below AA. Adjust lightness in OKLCH (keep hue and chroma), then re-run.`);
    if (argv.includes("--strict")) process.exit(1);
  }
}

if (import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith("tokens.mjs")) {
  main().catch((e) => {
    console.error(`ERR ${e.message}`);
    process.exit(1);
  });
}
